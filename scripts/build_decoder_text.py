#!/usr/bin/env python3
"""Combine scripts/i18n/<lang>/decoder_data_*.json into assets/decoder-data.<lang>.js (keys: hash of the English text,
see assets/decoder.js fnv()). Check afterwards: node scripts/decoder_strings.js check <lang>

Usage: py -3 scripts/build_decoder_text.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

for lang in ("fr", "ar"):
    parts = sorted((ROOT / "scripts" / "i18n" / lang).glob("decoder_data_*.json"))
    if not parts:
        continue
    data = {}
    for p in parts:
        chunk = json.loads(p.read_text(encoding="utf-8"))
        dup = set(chunk) & set(data)
        if dup:
            raise SystemExit(f"{p.name}: keys already set: {sorted(dup)[:5]}")
        data.update(chunk)
    body = json.dumps(data, ensure_ascii=False, indent=0, sort_keys=True)
    out = ROOT / "assets" / f"decoder-data.{lang}.js"
    out.write_text("/* Generated by scripts/build_decoder_text.py from scripts/i18n/" + lang + "/decoder_data_*.json. Do not edit. */\n"
                   "(function () {\n  var X = window.SD_DECODER_TEXT = window.SD_DECODER_TEXT || { text: {} };\n"
                   f"  X.data = {body};\n}})();\n", encoding="utf-8", newline="\n")
    print(f"{out.relative_to(ROOT)}: {len(data)} entries")
